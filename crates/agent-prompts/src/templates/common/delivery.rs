/// `<final_answer_instructions>`：最终回复必须独立成立。
///
/// 【出处：参考端 本地对照资料 18 §6「final_answer_instructions」】。
/// 逐条对应：独立成立 / 复述实质结果 / 多部分问题逐部分回答 / 点名文件改动 /
/// 不超 50–70 行。
pub(in crate::templates) const FINAL_ANSWER_INSTRUCTIONS: &str = "## 最终答复要求
- 中间的工具调用、观察、推理与进度消息在界面上是折叠或隐藏的，用户可能看不到原始输出——最终回复必须能独立成立。
- 复述每个实质结果：命令输出、检查过的路径、改动的文件、发现的结论、错误、未解决的风险与下一步。
- 多部分问题逐部分回答，或显式标出未解决的部分。
- 涉及文件改动时点名具体文件与改了什么。
- 回复不超过 50 到 70 行——给最高信号的上下文，而不是穷举。";

/// `<task_management>`：任务管理纪律。
///
/// 【出处：参考端 本地对照资料 18 §7「task_management 原文要点」+ 05 §4 R05-3
/// （≥3 个可独立验证步骤才建任务；状态流转准确）】。
pub(in crate::templates) const TASK_MANAGEMENT: &str = "## 任务管理
- 用任务清单工具跟踪任务并给用户可见的进度：对规划或拆解大任务尤其重要，不用就可能忘掉重要任务。
- 完成即标记完成，不得攒批——状态必须与实际进度一致。
- 启用条件：仅当请求有至少 3 个可独立验证的步骤，或用户明确要求拆解时才建任务；单条回复能解决的不建任务。
- 开始前标记进行中，做完立即标记完成，未完成的不得标记完成。";

/// `<task_management>`（plan 版）：plan 专属的两条。
///
/// 【出处：参考端 本地对照资料 21 §5「plan 的 task-management 比 craft 版
/// 多两个示例」+ 05 §5 plan 门禁状态机（未批准 ⇒ 只出方案不执行）】。
pub(in crate::templates) const TASK_MANAGEMENT_PLAN: &str = "## 规划态的任务管理
- 进入规划态后，把方案拆成可独立验证的步骤再建任务，批准后逐条推进。
- 计划未获批准前，任务只建不开始：不要把未执行的动作标记成进行中或已完成。";

/// `<example>`：行为锚点示例（craft 版：两个完整示例）。
///
/// 【出处：参考端 本地对照资料 18 §7「模板内嵌两个完整示例……示例即行为锚点，
