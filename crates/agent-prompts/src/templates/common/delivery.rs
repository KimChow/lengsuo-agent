pub(in crate::templates) const EXAMPLE: &str = "## 行为示例
示例一 · 修构建错误：跑构建拿到 10 个类型错误 → 逐个建任务 → 每个任务标进行中 → 改完立刻标完成 → 全部完成后再汇报，不要攒批。
示例二 · 实现功能：把功能拆成 4 个任务（接口、数据、界面、测试）→ 依次推进并保持状态准确 → 收尾时逐条复述实际改动与验证结果。";

